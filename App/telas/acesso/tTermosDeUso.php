                            A Prefeitura de Itapoá não garante a solução imediata de todos os problemas, uma vez que a resolução depende da complexidade das solicitações e dos recursos disponíveis para a equipe de suporte.<br>
                            A Prefeitura de Itapoá não será responsável por danos diretos ou indiretos causados pelo uso do SSPMI, incluindo perda de dados ou falhas no sistema que afetem a operação de outros sistemas internos da Prefeitura de Itapoá.
