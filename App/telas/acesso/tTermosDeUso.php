                            A Prefeitura de Itapoá se reserva o direito de modificar, atualizar ou alterar este Termo de Uso a qualquer momento, sem aviso prévio. Alterações significativas serão informadas aos usuários por meio de publicação no próprio sistema ou por outro meio de comunicação apropriado
                        </p>
