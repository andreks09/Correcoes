                        <h6 class="font-weight-bold">1. Introdução</h6>
                        <p>
                            Esse Termo de Uso regula o acesso e a utilização do SSPMI (Solicitação de Suporte da Prefeitura Municipal de Itapoá) aos servidores e prestadores de serviços da Prefeitura de Itapoá, com o objetivo de fornecer suporte para a abertura e gestão de <i>tickets</i> para a solução de problemas técnicos relacionados a tecnologia da informação.<br>
                            Ao acessar e utilizar o SSPMI, o usuário concorda com as disposições desse Termo de Uso. Caso não concorde com os termos aqui estabelecidos, o acesso ao sistema deve ser imediatamente interrompido.
                        </p>
                        <h6 class="font-weight-bold">2. Objetivo</h6>
                        <p>
                            O SSPMI tem como finalidade principal a gestão e acompanhamento de solicitações de suporte técnico, possibilitando a abertura de <i>tickets</i>, o acompanhamento do <i>status</i> das solicitações e a comunicação entre os usuários e a equipe de suporte.
                        </p>

                        <h6 class="font-weight-bold">3. Quem pode ultilizar o serviço</h6>
                        <p>
                            O SSPMI está disponível para:<br>
                            Servidores públicos e funcionários contratados ou de empresa terceirizada do executivo municipal de Itapoá que necessitem de suporte técnico para a resolução de problemas com sistemas e processos internos relacionados a informática.
                        </p>
                        <h6 class="font-weight-bold">4. Responsabilidade do usuário</h6>
                        <p>
                            O usuário compromete-se a:<br>
                            Utilizar o SSPMI exclusivamente para os fins previstos, relacionados à abertura de <i>tickets</i> e ao acompanhamento de solicitações de suporte.<br>
                            Fornecer informações corretas, claras e precisas ao abrir um <i>ticket</i>, de modo a garantir que o problema seja tratado de forma eficaz.<br>
                            Não utilizar o sistema para fins fraudulentos, ilícitos ou para a prática de atividades que possam prejudicar a operação do SSPMI, de outros sistemas ou a segurança das informações ali tratadas.<br>
                            Não compartilhar suas credenciais de acesso (<i>login</i> e senha). O usuário é o único responsável pela utilização do sistema através de sua conta de acesso.<br>
                            É expressamente proibido a compra e venda de contas de acesso ao SSPMI.<br>
                            Não é permitido publicar ou divulgar dados pessoais próprios ou de terceiros do sistema, seja no conteúdo dos <i>tickets</i> ou de qualquer outra forma. O usuário é responsável por manter a privacidade e segurança dos dados ao utilizar o sistema.<br>
                            Não modificar, traduzir, criar trabalhos derivados, nem aplicar engenharia reversa nos produtos e componentes do SSPMI. O acesso ao sistema é restrito ao uso conforme as funcionalidades previstas e expressamente autorizadas.<br>
                            Respeitar a legislação vigente e as normas internas da Prefeitura de Itapoá ao utilizar o SSPMI.
                        </p>
                        <h6 class="font-weight-bold">5. Responsabilidades da Prefeitura de Itapoá</h6>
                        <p>
                            O Departamento de Tecnologia da Informação, por meio do SSPMI, compromete-se a:<br>
                            Oferecer um sistema de suporte eficiente para a abertura e acompanhamento de <i>tickets</i>, com o objetivo de resolver problemas técnicos de forma tempestiva.<br>
                            Manter a confidencialidade das informações compartilhadas pelos usuários durante a abertura e o acompanhamento de <i>tickets</i>, conforme a política de privacidade e as normas legais aplicáveis.<br>
                            Fornecer um canal de comunicação transparente e eficiente entre os usuários e a equipe de suporte.<br>
                            Gerar relatórios quando solicitado para atender as demandas administrativas.
                        </p>
                        <h6 class="font-weight-bold">6. Política de privacidade</h6>
                        <p>
                            O Departamento da Tecnologia da Informação compromete-se a proteger a privacidade dos usuários ao acessar o SSPMI. As informações fornecidas pelos usuários durante a abertura de <i>tickets</i> serão tratadas conforme a legislação de proteção de dados pessoais aplicável, incluindo a Lei Geral de Proteção de Dados Pessoais (LGPD), e serão utilizadas exclusivamente para os fins relacionados ao suporte solicitado ou para apurar fatos que decorram de processos administrativos.
