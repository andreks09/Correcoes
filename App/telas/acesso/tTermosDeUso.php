                    <p>
                        1. <b>INTRODUÇÃO</b><br>
                        
                        Esse Termo de Uso regula o acesso e a utilização do SSPMI (Solicitação de Suporte da Prefeitura Municipal de Itapoá) aos servidores e prestadores de serviços da Prefeitura de Itapoá, com o objetivo de fornecer suporte para a abertura e gestão de <i>tickets</i> para a solução de problemas técnicos relacionados a tecnologia da informação.<br>
                        <br>
                        Ao acessar e utilizar o SSPMI, o usuário concorda com as disposições desse Termo de Uso. Caso não concorde com os termos aqui estabelecidos, o acesso ao sistema deve ser imediatamente interrompido.<br>
                        <br>
                        2. <b>OBJETIVO</b><br>

                        O SSPMI tem como finalidade principal a gestão e acompanhamento de solicitações de suporte técnico, possibilitando a abertura de <i>tickets</i>, o acompanhamento do status das solicitações e a comunicação entre os usuários e a equipe de suporte.<br>
                        <br>
                        3. <b>QUEM PODE UTILIZAR O SERVIÇO</b><br>
                        <br>
                        O SSPMI está disponível para:<br>

                        3.1. Servidores públicos e funcionários contratados ou de empresa terceirizada do executivo municipal de Itapoá que necessitem de suporte técnico para a resolução de problemas com sistemas e processos internos relacionados a informática.<br>
                        <br>
                        4. <b>RESPONSABILIDADES DO USUÁRIO</b><br>

                        O usuário compromete-se a:<br>

                        4.1. Utilizar o SSPMI exclusivamente para os fins previstos, relacionados à abertura de <i>tickets</i> e ao acompanhamento de solicitações de suporte.<br>
                        <br>
                        4.2. Fornecer informações corretas, claras e precisas ao abrir um <i>ticket</i>, de modo a garantir que o problema seja tratado de forma eficaz.<br>
                        <br>
                        4.3. Não utilizar o sistema para fins fraudulentos, ilícitos ou para a prática de atividades que possam prejudicar a operação do SSPMI, de outros sistemas ou a segurança das informações ali tratadas.<br>
                        <br>
                        4.4. Não compartilhar suas credenciais de acesso (<i>login</i> e senha). O usuário é o único responsável pela utilização do sistema através de sua conta de acesso.<br>
                        <br>
                        4.5. É expressamente proibido a compra e venda de contas de acesso ao SSPMI.<br>
                        <br>
                        4.6. Não é permitido publicar ou divulgar dados pessoais próprios ou de terceiros do sistema, seja no conteúdo dos <i>tickets</i> ou de qualquer outra forma. O usuário é responsável por manter a privacidade e segurança dos dados ao utilizar o sistema.<br>
                        <br>
                        4.7. Não modificar, traduzir, criar trabalhos derivados, nem aplicar engenharia reversa nos produtos e componentes do SSPMI. O acesso ao sistema é restrito ao uso conforme as funcionalidades previstas e expressamente autorizadas.<br>
                        <br>
                        4.8. Respeitar a legislação vigente e as normas internas da Prefeitura de Itapoá ao utilizar o SSPMI.<br>
                        <br>
                        5. <b>RESPONSABILIDADES DA PREFEITURA DE ITAPOÁ</b><br>

                        O Departamento de Tecnologia da Informação, por meio do SSPMI, compromete-se a:<br>
                        <br>
                        5.1. Oferecer um sistema de suporte eficiente para a abertura e acompanhamento de <i>tickets</i>, com o objetivo de resolver problemas técnicos de forma tempestiva.<br>
                        <br>
                        5.2. Manter a confidencialidade das informações compartilhadas pelos usuários durante a abertura e o acompanhamento de <i>tickets</i>, conforme a política de privacidade e as normas legais aplicáveis.<br>
                        <br>
                        5.3. Fornecer um canal de comunicação transparente e eficiente entre os usuários e a equipe de suporte.<br>
                        <br>
                        5.4. Gerar relatórios quando solicitado para atender a demandas administrativas.<br>
                        <br>
                        6. <b>POLÍTICA DE PRIVACIDADE</b><br>
                        <br>
                        O Departamento da Tecnologia da Informação compromete-se a proteger a privacidade dos usuários ao acessar o SSPMI. As informações fornecidas pelos usuários durante a abertura de <i>tickets</i> serão tratadas conforme a legislação de proteção de dados pessoais aplicável, incluindo a Lei Geral de Proteção de Dados Pessoais (LGPD), e serão utilizadas exclusivamente para os fins relacionados ao suporte solicitado ou para apurar fatos que decorram de processos administrativos.<br>
                        <br> 
                        7. <b>LIMITAÇÃO DE RESPONSABILIDADE</b><br>
                        
                        7.1. A Prefeitura de Itapoá não se responsabiliza por eventuais problemas decorrentes do uso indevido do Portal SSPMI por parte dos usuários.<br>
                        <br>
                        7.2. A Prefeitura de Itapoá não garante a solução imediata de todos os problemas, uma vez que a resolução depende da complexidade das solicitações e dos recursos disponíveis para a equipe de suporte.<br>
                        <br>
                        7.3. A Prefeitura de Itapoá não será responsável por danos diretos ou indiretos causados pelo uso do SSPMI, incluindo perda de dados ou falhas no sistema que afetem a operação de outros sistemas internos da Prefeitura de Itapoá.<br>
                        <br>
                        8. <b>ALTERAÇÕES E ATUALIZAÇÕES</b><br>

                        A Prefeitura de Itapoá se reserva o direito de modificar, atualizar ou alterar este Termo de Uso a qualquer momento, sem aviso prévio. Alterações significativas serão informadas aos usuários por meio de publicação no próprio sistema ou por outro meio de comunicação apropriado.<br>
                        <br>
                        9. <b>VIGÊNCIA</b><br>

                        Este Termo de Uso entra em vigor na data de sua publicação e permanecerá válido enquanto o usuário utilizar o SSPMI.<br>
                        <br>
                        10. <b>DISPOSIÇÕES FINAIS</b><br>

                        10.1. O não cumprimento de qualquer uma das disposições deste Termo de Uso pode resultar em processo administrativo.<br>
                        <br>
                        10.2. Qualquer dúvida ou questionamento sobre este Termo de Uso deve ser direcionado à equipe de suporte do Departamento da Tecnologia da Informação, por meio dos canais de comunicação oficiais.<br>
                        <br>
                        12. <b>USO DE <i>COOKIES</i></b><br>

                        12.1. Como usamos os <i>cookies?</i><br>

                        O SSPMI utiliza <i>cookies</i> para:<br>
                        <br>
                        Melhorar a navegação: tornando o uso mais eficiente e agradável.<br>
                        <br>
                        Autenticação e segurança: <i>Cookies</i> podem ser utilizados para armazenar informações de login e garantir que o usuário tenha acesso a suas solicitações de suporte de maneira segura.<br>
                        <br>
                        Análise: Utilizamos <i>cookies</i> para coletar informações sobre o uso do sistema, como, pagina do SSPMI acessada, IP, navegador, sdesempenhoistema operacional e nome do dispositivo. Essas informações são coletadas para armazenar o log do sistema afim de armazena-las para auditorias futuras.<br>
                        <br>
                        12.3. Controle de <i>cookies</i><br>
                        
                        Os usuários podem configurar seus navegadores para aceitar ou rejeitar <i>cookies</i>, ou para ser notificados sempre que um <i>cookie</i> for enviado. A maioria dos navegadores permite que o usuário aceite ou recuse os cookies por padrão. No entanto, ao desabilitar os <i>cookies</i>, o usuário pode não conseguir acessar determinadas funcionalidades do Sistema SSPMI.<br>
                        <br>
                        12.4. Consentimento para o uso de cookies<br>
                        <br>
                        Ao acessar e utilizar o SSPMI, o usuário concorda com o uso de <i>cookies</i> conforme descrito neste Termo de Uso. Caso o usuário não concorde com o uso de <i>cookies</i>, é recomendável que ajuste as configurações de seu navegador ou interrompa o uso do sistema.<br>
                        
                        12.5. Alterações no uso de <i>cookies</i><br>
                        <br>
                        O Departamento da Tecnologia da Informação se reserva o direito de alterar a forma como utiliza cookies no Sistema SSPMI, sendo qualquer modificação comunicada aos usuários de maneira apropriada, por meio de atualizações deste Termo de Uso ou através de outras formas de comunicação disponíveis no sistema.<br>
